#!/usr/bin/env node
"use strict";

// Scans app/api for route.ts files and generates server/routes.generated.ts —
// the route table the embedded server dispatches against. Mirrors Next's
// file-system routing: [param] matches one segment, [...param] matches the rest.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const apiDir = path.join(root, "app", "api");
const outFile = path.join(root, "server", "routes.generated.ts");

function walk(dir) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...walk(full));
    else if (entry.name === "route.ts") found.push(full);
  }
  return found;
}

const routeFiles = walk(apiDir).sort();
const entries = routeFiles.map((file, index) => {
  const relDir = path.relative(apiDir, path.dirname(file)).split(path.sep).join("/");
  const pattern = "/api" + (relDir ? "/" + relDir : "");
  const importPath = "../app/api/" + (relDir ? relDir + "/" : "") + "route";
  return { pattern, importPath, index };
});

const lines = [
  "// GENERATED by bin/build-route-manifest.js — do not edit by hand.",
  "/* eslint-disable */",
  "// @ts-nocheck — its app/api imports vanish while api is stashed during the export build.",
  ...entries.map((e) => `import * as r${e.index} from "${e.importPath}";`),
  "",
  "export interface RouteEntry { pattern: string; module: Record<string, unknown> }",
  "export const routes: RouteEntry[] = [",
  ...entries.map((e) => `  { pattern: ${JSON.stringify(e.pattern)}, module: r${e.index} as Record<string, unknown> },`),
  "];",
  "",
];

fs.writeFileSync(outFile, lines.join("\n"));
console.log(`route-manifest: ${entries.length} routes -> ${path.relative(root, outFile)}`);
